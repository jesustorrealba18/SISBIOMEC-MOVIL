const atletasSlice = createSlice({
  name: 'atletas',
  initialState,
  reducers: {
    addAtleta: {
      reducer(state, action) {
        state.unshift(action.payload);
      },
      prepare(datos) {
        return { payload: { id: nanoid(6), ...datos } };
      },
    },
    updateAtleta(state, action) {
      const indice = state.findIndex((atleta) => atleta.id === action.payload.id);
      if (indice !== -1) {
        state[indice] = action.payload;
      }
    },
    deleteAtleta(state, action) {
      return state.filter((atleta) => atleta.id !== action.payload);
    },
  },
});

export const { addAtleta, updateAtleta, deleteAtleta } = atletasSlice.actions;
export default atletasSlice.reducer;
